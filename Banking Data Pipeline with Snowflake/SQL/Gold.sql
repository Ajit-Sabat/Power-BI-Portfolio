INSERT INTO FACT_LOAN_PAYMENT (
    PAYMENT_ID,
    PAYMENT_DATE,
    LOAN_KEY,
    CUSTOMER_KEY,
    PAYMENT_AMOUNT,
    PRINCIPAL_AMOUNT,
    INTEREST_AMOUNT,
    PAYMENT_STATUS
)
SELECT
    p.PAYMENT_ID,
    p.PAYMENT_DATE,
    l.LOAN_KEY,
    c.CUSTOMER_KEY,
    p.PAYMENT_AMOUNT,
    p.PRINCIPAL_AMOUNT,
    p.INTEREST_AMOUNT,
    p.PAYMENT_STATUS
FROM BANKING_DWH.SILVER.SILVER_LOAN_PAYMENT p
JOIN DIM_LOAN l
    ON p.LOAN_ID = l.LOAN_ID
JOIN DIM_CUSTOMER c
    ON p.CUSTOMER_ID = c.CUSTOMER_ID
    AND p.PAYMENT_DATE >= c.EFFECTIVE_FROM::DATE
    AND (
        p.PAYMENT_DATE < c.EFFECTIVE_TO::DATE
        OR c.EFFECTIVE_TO IS NULL
    );

