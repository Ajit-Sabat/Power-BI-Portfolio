USE DATABASE BANKING_DWH;
USE SCHEMA GOLD;


CREATE TABLE DIM_CUSTOMER (
    CUSTOMER_KEY NUMBER AUTOINCREMENT,
    CUSTOMER_ID VARCHAR,
    FIRST_NAME VARCHAR,
    LAST_NAME VARCHAR,
    GENDER VARCHAR,
    DATE_OF_BIRTH DATE,
    CITY VARCHAR,
    REGION VARCHAR,
    CUSTOMER_SEGMENT VARCHAR,
    CUSTOMER_STATUS VARCHAR,
    EFFECTIVE_FROM TIMESTAMP_NTZ,
    EFFECTIVE_TO TIMESTAMP_NTZ,
    IS_CURRENT BOOLEAN
);

CREATE TABLE DIM_ACCOUNT (
    ACCOUNT_KEY NUMBER AUTOINCREMENT,
    ACCOUNT_ID VARCHAR,
    CUSTOMER_ID VARCHAR,
    PRODUCT_ID VARCHAR,
    ACCOUNT_TYPE VARCHAR,
    ACCOUNT_STATUS VARCHAR,
    OPEN_DATE DATE
);


CREATE TABLE DIM_LOAN (
    LOAN_KEY NUMBER AUTOINCREMENT,
    LOAN_ID VARCHAR,
    CUSTOMER_ID VARCHAR,
    LOAN_TYPE VARCHAR,
    LOAN_AMOUNT NUMBER(18,2),
    INTEREST_RATE NUMBER(10,4),
    START_DATE DATE,
    MATURITY_DATE DATE,
    LOAN_STATUS VARCHAR,
    OUTSTANDING_AMOUNT NUMBER(18,2)
);



CREATE TABLE FACT_TRANSACTION (
    TRANSACTION_KEY NUMBER AUTOINCREMENT,
    TRANSACTION_ID VARCHAR,
    TRANSACTION_DATE DATE,
    ACCOUNT_KEY NUMBER,
    CUSTOMER_KEY NUMBER,
    TRANSACTION_TYPE VARCHAR,
    TRANSACTION_AMOUNT NUMBER(18,2),
    TRANSACTION_CHANNEL VARCHAR,
    TRANSACTION_STATUS VARCHAR
);



CREATE TABLE FACT_LOAN_PAYMENT (
    PAYMENT_KEY NUMBER AUTOINCREMENT,
    PAYMENT_ID VARCHAR,
    PAYMENT_DATE DATE,
    LOAN_KEY NUMBER,
    CUSTOMER_KEY NUMBER,
    PAYMENT_AMOUNT NUMBER(18,2),
    PRINCIPAL_AMOUNT NUMBER(18,2),
    INTEREST_AMOUNT NUMBER(18,2),
    PAYMENT_STATUS VARCHAR
);

