INSERT INTO FACT_TRANSACTION (
    TRANSACTION_ID,
    TRANSACTION_DATE,
    ACCOUNT_KEY,
    CUSTOMER_KEY,
    TRANSACTION_TYPE,
    TRANSACTION_AMOUNT,
    TRANSACTION_CHANNEL,
    TRANSACTION_STATUS
)
SELECT
    t.TRANSACTION_ID,
    t.TRANSACTION_DATE,
    a.ACCOUNT_KEY,
    c.CUSTOMER_KEY,
    t.TRANSACTION_TYPE,
    t.TRANSACTION_AMOUNT,
    t.TRANSACTION_CHANNEL,
    t.TRANSACTION_STATUS
FROM BANKING_DWH.SILVER.SILVER_TRANSACTION t
JOIN DIM_ACCOUNT a
    ON t.ACCOUNT_ID = a.ACCOUNT_ID
JOIN DIM_CUSTOMER c
    ON t.CUSTOMER_ID = c.CUSTOMER_ID
    AND t.TRANSACTION_DATE >= c.EFFECTIVE_FROM::DATE
    AND (
        t.TRANSACTION_DATE < c.EFFECTIVE_TO::DATE
        OR c.EFFECTIVE_TO IS NULL
    );

